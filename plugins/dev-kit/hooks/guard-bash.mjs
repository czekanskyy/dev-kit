function ghJson(ctx, args, cwd) {
  return JSON.parse(ctx.exec('gh', args, { cwd, timeout: GH_TIMEOUT }));
}

function evalGh(cmd, ctx, state, out) {
  const [, group, sub, ...rest] = cmd.argv;
  const deny = (reason) => out.push({ decision: 'deny', reason });
  const ask = (reason) => out.push({ decision: 'ask', reason });
  const config = ctx.config;

  if (group === 'pr' && (sub === 'create' || sub === 'edit')) {
    const o = parseOpts(rest, {
      short: 'tbFBHalmprRTe',
      long: ['title', 'body', 'body-file', 'base', 'head', 'assignee', 'label', 'milestone', 'project', 'reviewer', 'template', 'repo', 'add-label', 'remove-label', 'add-reviewer', 'remove-reviewer', 'add-assignee', 'remove-assignee', 'add-project', 'remove-project', 'recover'],
    });
    const texts = [...(o.values.t ?? []), ...(o.values.title ?? []), ...(o.values.b ?? []), ...(o.values.body ?? [])];
    for (const f of [...(o.values.F ?? []), ...(o.values['body-file'] ?? [])]) texts.push(readMessageFile(f, state.cwd, cmd));
    checkMessage(texts, 'Pull request text', config, out);
    return;
  }
  if (group === 'pr' && sub === 'merge') {
    evalPrMerge(rest, ctx, state, out);
    return;
  }
  if (group === 'api') {
    const args = cmd.argv.slice(2);
    const o = parseOpts(args, { short: 'XfFHpqt', long: ['method', 'raw-field', 'field', 'header', 'preview', 'jq', 'template', 'input', 'cache', 'hostname'] });
    const endpoint = String(o.pos[0] ?? '').replace(/^https:\/\/api\.github\.com\//, '').replace(/^\//, '');
    const hasFields = ['f', 'F', 'raw-field', 'field', 'input'].some((f) => o.flags.has(f));
    const method = String(o.values.X?.[0] ?? o.values.method?.[0] ?? (hasFields ? 'POST' : 'GET')).toUpperCase();
    if (endpoint === 'graphql') {
      const q = [...(o.values.f ?? []), ...(o.values.F ?? []), ...(o.values['raw-field'] ?? []), ...(o.values.field ?? [])].join('\n');
      if (/\bmutation\b/i.test(q)) ask('gh api graphql mutation: it can change repository state. Confirm this change.');
      return;
    }
    if (/^repos\/[^/]+\/[^/]+/.test(endpoint) && WRITE_METHODS.has(method)) {
      const isStatus = method === 'POST' && /^repos\/[^/]+\/[^/]+\/statuses\/[^/]+$/.test(endpoint);
      const isComment =
        (method === 'POST' || method === 'PATCH') &&
        /^repos\/[^/]+\/[^/]+\/(issues|pulls)\/(\d+\/comments|comments\/\d+|comments\/\d+\/replies|\d+\/comments\/\d+\/replies)$/.test(endpoint);
      if (!isStatus && !isComment) {
        deny(`gh api ${method} ${endpoint} refused: repository settings, branches, rulesets, hooks and collaborators are managed by a human. Ask the user to make this change.`);
      }
    } else if (WRITE_METHODS.has(method) && !/^repos\//.test(endpoint)) {
      ask(`gh api ${method} ${endpoint}: a write outside a repository. Confirm this change.`);
    }
    return;
  }
  if (group === 'repo' && ['edit', 'delete', 'rename', 'archive', 'unarchive'].includes(sub)) {
    deny(`gh repo ${sub} refused: repository settings are managed by a human.`);
    return;
  }
  if (group === 'secret') {
    deny('gh secret refused: secrets are managed by a human. Ask the user to set it.');
    return;
  }
  if (group === 'variable' && ['set', 'delete'].includes(sub)) {
    deny(`gh variable ${sub} refused: repository variables are managed by a human.`);
    return;
  }
  if (group === 'auth' && sub === 'token') {
    deny('gh auth token refused: it prints a credential. gh commands authenticate on their own.');
    return;
  }
  if (group === 'auth' && sub === 'status' && rest.some((a) => a === '--show-token' || a === '-t')) {
    deny('gh auth status --show-token refused: it prints a credential. Use gh auth status without it.');
  }
}

function evalPrMerge(args, ctx, state, out) {
  const deny = (reason) => out.push({ decision: 'deny', reason });
  const ask = (reason) => out.push({ decision: 'ask', reason });
  const config = ctx.config;
  const br = branchesOf(config);
  const o = parseOpts(args, { short: 'tbFAR', long: ['subject', 'body', 'body-file', 'author-email', 'match-head-commit', 'repo'] });
  if (o.flags.has('admin')) {
    deny('gh pr merge --admin refused: it bypasses branch protection. Get the required checks and reviews green instead.');
    return;
  }
  checkMessage([...(o.values.t ?? []), ...(o.values.subject ?? []), ...(o.values.b ?? []), ...(o.values.body ?? [])], 'Merge commit text', config, out);
  const repo = o.values.R?.[0] ?? o.values.repo?.[0];
  const repoArgs = repo ? ['--repo', repo] : [];
  const sel = o.pos[0];
  const cwd = state.cwd;
  let pr;
  try {
    pr = ghJson(ctx, ['pr', 'view', ...(sel ? [sel] : []), '--json', 'baseRefName,headRefOid,headRefName,files', ...repoArgs], cwd);
  } catch {
    ask('gh pr merge: could not look up the pull request (gh failed), so its base branch is unknown. Confirm the merge.');
    return;
  }
  const base = pr.baseRefName;
  if (br.protected.has(base)) {
    deny(`gh pr merge refused: the pull request targets protected branch "${base}". Merging there is for a human.`);
    return;
  }
  if (!br.integration || base !== br.integration) return;

  const sha = pr.headRefOid;
  const statusContext = config.gate?.statusContext || 'local-gate';
  try {
    const nwo = repo ?? ghJson(ctx, ['repo', 'view', '--json', 'nameWithOwner'], cwd).nameWithOwner;
    const status = ghJson(ctx, ['api', `repos/${nwo}/commits/${sha}/status`], cwd);
    const entry = (status.statuses ?? []).find((s) => s.context === statusContext);
    if (!entry || entry.state !== 'success') {
      deny(`gh pr merge refused: commit status "${statusContext}" on ${String(sha).slice(0, 12)} is ${entry ? entry.state : 'missing'}. Run the gate (node scripts/gate.mjs --post-status) on that exact commit first.`);
    }
  } catch {
    ask(`gh pr merge: could not read the "${statusContext}" commit status (gh failed). Confirm the gate passed on ${String(sha).slice(0, 12)}.`);
  }

  const remoteRef = `${br.remote}/${br.integration}`;
  let haveSha = true;
  try {
    ctx.exec('git', ['cat-file', '-e', `${sha}^{commit}`], { cwd, timeout: GH_TIMEOUT });
  } catch {
    haveSha = false;
  }
  if (!haveSha) {
    ask(`gh pr merge: the pull request head ${String(sha).slice(0, 12)} is not in the local repository, so it cannot be checked against ${remoteRef}. Fetch first, or confirm.`);
  } else {
    try {
      ctx.exec('git', ['merge-base', '--is-ancestor', remoteRef, sha], { cwd, timeout: GH_TIMEOUT });
    } catch (err) {
      if (err && err.status === 1) {
        deny(`gh pr merge refused: the pull request head does not contain the current ${remoteRef}. Rebase the branch onto ${remoteRef}, rerun the gate and push again.`);
      } else {
        ask(`gh pr merge: could not compare the head with ${remoteRef}. Confirm the branch is up to date.`);
      }
    }
  }

  try {
    const files = (pr.files ?? []).map((f) => f.path);
    const risk = analyzeRisk({ cwd, config, pr: sel ?? pr.headRefName, repo, prFiles: files, baseRefName: base, exec: ctx.exec });
    if (risk.touchesRisk) {
      const list = [...risk.riskFiles, ...risk.contentHits.map((h) => `${h.file}:${h.line}`)].slice(0, 8).join(', ');
      ask(`gh pr merge: this pull request touches risk paths (${list}). The user approves risky merges.`);
    }
  } catch {
    ask('gh pr merge: the risk check failed. Confirm the merge.');
  }
}

